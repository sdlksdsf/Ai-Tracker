/** Convert a corpus entry into the same shape the LLM providers return. */
export function toAiRecipe(entry: CorpusRecipe, opts: { servings?: number; model?: string } = {}): AiRecipe {
  const servings = opts.servings ?? entry.servings;
  const scale = servings / entry.servings;

  const ingredients: AiRecipeIngredient[] = entry.ingredients.map(([name, qty, unit]) => ({
    name,
    quantity: qty === null ? null : Math.round(qty * scale * 100) / 100,
    unit,
    category: coerceCategory(name),
    is_in_pantry: false,
    is_optional: false,
    substitutes: [],
  }));

  return {
    title: entry.title,
    description: entry.description,
    cuisine: entry.cuisine,
    meal_type: entry.mealType,
    difficulty: entry.difficulty,
    prep_time_min: entry.prepTimeMin,
    cook_time_min: entry.cookTimeMin,
    total_time_min: entry.prepTimeMin + entry.cookTimeMin,
    servings,
    tags: [...entry.tags, entry.mealType],
    ingredients,
    steps: entry.steps.map(([instruction, durationMin, tip], index) => ({
      step_number: index + 1,
      instruction,
      duration_min: durationMin,
      tip: tip ?? null,
    })),
    estimated_nutrition_per_serving: {
      calories: Math.round(entry.nutrition.calories * (scale > 0 ? 1 : 1)),
      protein_g: entry.nutrition.protein_g,
      carbs_g: entry.nutrition.carbs_g,
      fat_g: entry.nutrition.fat_g,
      fiber_g: entry.nutrition.fiber_g,
      sodium_mg: entry.nutrition.sodium_mg,
    },
    allergen_warnings: [],
    storage_instructions: entry.storage,
    reheating_instructions: entry.reheating ?? null,
    estimated_cost: round2(ingredients.reduce((sum, i) => sum + estimatePriceUsd(i.name, i.quantity, i.unit), 0) / servings),
  };
}

function round2(n: number): number {
  return Math.round(n * 100) / 100;
}

